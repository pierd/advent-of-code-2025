use std::fmt::Debug;

use crate::types::Point2d;

fn rect_area([x, y]: Point2d, [x2, y2]: Point2d) -> u64 {
    (x.abs_diff(x2) + 1) * (y.abs_diff(y2) + 1)
}

pub fn solve_part1(points: &[Point2d]) -> u64 {
    points
        .iter()
        .enumerate()
        .flat_map(|(idx, p)| points.iter().skip(idx + 1).map(|p2| rect_area(*p, *p2)))
        .max()
        .unwrap()
}

trait Line {
    fn start(&self) -> Point2d;
    fn end(&self) -> Point2d;

    fn vertical(&self) -> Option<u64> {
        // same X |
        (self.start()[0] == self.end()[0]).then_some(self.start()[0])
    }
    fn horizontal(&self) -> Option<u64> {
        // same Y -
        (self.start()[1] == self.end()[1]).then_some(self.start()[1])
    }
    fn min_x(&self) -> u64 {
        self.start()[0].min(self.end()[0])
    }
    fn max_x(&self) -> u64 {
        self.start()[0].max(self.end()[0])
    }
    fn min_y(&self) -> u64 {
        self.start()[1].min(self.end()[1])
    }
    fn max_y(&self) -> u64 {
        self.start()[1].max(self.end()[1])
    }
}
impl Line for (Point2d, Point2d) {
    fn start(&self) -> Point2d {
        self.0
    }
    fn end(&self) -> Point2d {
        self.1
    }
}
impl Line for &[Point2d; 2] {
    fn start(&self) -> Point2d {
        self[0]
    }
    fn end(&self) -> Point2d {
        self[1]
    }
}
impl Line for [Point2d; 2] {
    fn start(&self) -> Point2d {
        self[0]
    }
    fn end(&self) -> Point2d {
        self[1]
    }
}

fn outline_lines(outline: &[Point2d]) -> impl Iterator<Item = [Point2d; 2]> + '_ {
    let len = outline.len();
    (0..len).map(move |i| [outline[i], outline[(i + 1) % len]])
}

fn lines_cross<L: Line + Debug, L2: Line + Debug>(line: L, line2: L2) -> bool {
    debug_assert!(line.horizontal().is_some() || line.vertical().is_some());
    debug_assert!(line2.horizontal().is_some() || line2.vertical().is_some());
    if line.horizontal().is_some() == line2.horizontal().is_some() {
        // both horizontal or both vertical -> no crossing
        false
    } else if let (Some(y), Some(x)) = (line.horizontal(), line2.vertical()) {
        (line.min_x() < x) && (x < line.max_x()) && (line2.min_y() < y) && (y < line2.max_y())
    } else if let (Some(x), Some(y)) = (line.vertical(), line2.horizontal()) {
        (line.min_y() < y) && (y < line.max_y()) && (line2.min_x() < x) && (x < line2.max_x())
    } else {
        unreachable!()
    }
}

fn crosses_any_line<L: Line + Debug + Copy>(line: L, outline: &[Point2d]) -> bool {
    outline_lines(outline).any(|outline_line| lines_cross(line, outline_line))
}

fn point_on_line<L: Line>(p: Point2d, line: L) -> bool {
    if let Some(x) = line.vertical() {
        x == p[0] && line.min_y() <= p[1] && p[1] <= line.max_y()
    } else if let Some(y) = line.horizontal() {
        y == p[1] && line.min_x() <= p[0] && p[0] <= line.max_x()
    } else {
        panic!("line should be either vertical or horizontal")
    }
}

fn point_inside(p: Point2d, outline: &[Point2d]) -> bool {
    // check if the point is on the boundary (fast pass)
    if outline_lines(outline).any(|line| point_on_line(p, line)) {
        return true;
    }
    // check if the point is actually inside with raytracing
    let [x, y] = p;
    outline_lines(outline).fold(false, |inside, line| {
        if line.horizontal().is_some() {
            // only vertical edges matter for a horizontal ray cast -> don't flip the flag
            inside
        } else if let Some(line_x) = line.vertical() {
            // does the horizontal ray at height y cross this vertical edge?
            if line.min_y() <= y && y < line.max_y() && x < line_x {
                // crossing -> flip
                !inside
            } else {
                // not crossing -> don't flip
                inside
            }
        } else {
            // shouldn't happen
            panic!("line should be either vertical or horizontal");
        }
    })
}

pub fn solve_part2(points: &[Point2d]) -> (u64, Point2d, Point2d) {
    let mut candidates: Vec<_> = points
        .iter()
        .enumerate()
        .flat_map(|(idx, p)| {
            points
                .iter()
                .skip(idx + 1)
                .map(|p2| (rect_area(*p, *p2), *p, *p2))
        })
        .collect();
    candidates.sort_unstable();
    candidates.reverse();
    for (area, [x, y], [x2, y2]) in candidates {
        if [
            // [x, y],   // must already be inside
            // [x2, y2], // must already be inside
            [x, y2],
            [x2, y],
        ]
        .iter()
        .any(|point| !point_inside(*point, points))
            || [
                ([x, y], [x2, y]),
                ([x2, y], [x2, y2]),
                ([x2, y2], [x, y2]),
                ([x, y2], [x, y]),
            ]
            .iter()
            .any(|line| crosses_any_line(*line, points))
        {
            continue;
        }
        return (area, [x, y], [x2, y2]);
    }
    unreachable!("no suitable candidate found")
}

